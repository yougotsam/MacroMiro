/**
 * Generated status page. The test fails if docs/status/SNAPSHOT.md drifts from these constants.
 * Run: bun scripts/deskc/status-snapshot.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import {
  APPROVAL_POLICY_ENFORCED,
  CALIBRATED_MODEL_APPROVED,
  DAILY_STOP_USD,
  MODEL_VERSION,
  RISK_LIMITS,
} from "../../src/lib/desk/config";

export const SNAPSHOT_PATH = "docs/status/SNAPSHOT.md";

export function renderStatusSnapshot(): string {
  const gate = APPROVAL_POLICY_ENFORCED
    ? "round-3 calibrator policy ENFORCED"
    : "pre-round-3 gate path ACTIVE; round-3 calibrator policy PROPOSED / NOT ENFORCED";
  const u = RISK_LIMITS.usd;
  return [
    "# Status snapshot",
    "",
    "Generated by `scripts/deskc/status-snapshot.ts` from `src/lib/desk/config.ts`. Do not hand-edit.",
    "",
    `- MODEL_VERSION: \`${MODEL_VERSION}\``,
    `- CALIBRATED_MODEL_APPROVED: ${CALIBRATED_MODEL_APPROVED}`,
    `- APPROVAL_POLICY_ENFORCED: ${APPROVAL_POLICY_ENFORCED}`,
    `- Active gate path: ${gate}`,
    `- DAILY_STOP_USD: ${DAILY_STOP_USD}`,
    `- open worst cap: ${u.total}`,
    `- per order: ${u.perOrder}`,
    `- per ticker: ${u.perTicker}`,
    `- correlated same-direction: ${u.correlated}`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const body = renderStatusSnapshot();
  mkdirSync(dirname(SNAPSHOT_PATH), { recursive: true });
  writeFileSync(SNAPSHOT_PATH, body);
  process.stdout.write(body);
}
